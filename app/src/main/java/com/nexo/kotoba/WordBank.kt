    private fun enNumberWords(): List<Word> {
        val out = mutableListOf<Word>()
        for (i in 1..100) out += Word("wbn-en-$i", "🔢", enKata(i), enName(i).replace("-", ""), "", enName(i), "", hiNum[i - 1])
        return out
    }

    private fun jaNumberWords(): List<Word> {
        val ones = arrayOf("", "いち", "に", "さん", "よん", "ご", "ろく", "なな", "はち", "きゅう")
        val onesK = arrayOf("", "一", "二", "三", "四", "五", "六", "七", "八", "九")
        val onesR = arrayOf("", "ichi", "ni", "san", "yon", "go", "roku", "nana", "hachi", "kyuu")
        val out = mutableListOf<Word>()
        for (i in 1..100) {
            val (k, kk, r) = when {
                i == 100 -> Triple("ひゃく", "百", "hyaku")
                i <= 9 -> Triple(ones[i], onesK[i], onesR[i])
                i == 10 -> Triple("じゅう", "十", "juu")
                i < 20 -> { val o = i - 10; Triple("じゅう" + ones[o], "十" + onesK[o], "juu" + onesR[o]) }
                i % 10 == 0 -> { val t = i / 10; Triple(ones[t] + "じゅう", onesK[t] + "十", onesR[t] + "juu") }
                else -> { val t = i / 10; val o = i % 10; Triple(ones[t] + "じゅう" + ones[o], onesK[t] + "十" + onesK[o], onesR[t] + "juu" + onesR[o]) }
            }
            out += Word("wbn-ja-$i", "🔢", k, r, kk, enName(i), "", hiNum[i - 1])
        }
        return out
    }

